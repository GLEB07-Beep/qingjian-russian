def sanitize_sense(pos: str, body: str) -> str | None:
    """对单个译词执行青简门禁规则过滤与规范化。"""
    body = body.strip()
    if not body:
        return None
    if len(body) > MAX_GLOSS_CHARS:
        return None
    if len(body.split()) > MAX_GLOSS_WORDS:
        return None
    if re.search(r"[a-zA-Z]", body):
        return None
    if re.search(r"[\u4e00-\u9fff]", body):
        return None
    if not CYRILLIC_PATTERN.match(body):
        return None
    if pos and pos not in ALLOWED_POS:
        return None
    if pos == "v.":
        clean_b = body.replace("\u0301", "").strip().lower()
        if not clean_b.split()[-1].endswith(INFINITIVE_ENDINGS):
            return None
    return f"{pos} {body}" if pos else body


def extract_from_rich(rich_path: Path) -> dict[str, list[str]]:
    """从 WorkBuddy 的 ru-data.js 中提炼合格释义。"""
    if not rich_path.is_file():
        return {}

    text = rich_path.read_text(encoding="utf-8", errors="ignore")
    m = re.search(r"window\.RU_DATA\s*=\s*(\{[\s\S]*\});?\s*$", text)
    if not m:
        return {}

    try:
        data = json.loads(m.group(1))
    except Exception:
        return {}

    rich = data.get("RICH", [])
    pos_map = {
        "noun": "n.",
        "verb": "v.",
        "adj": "adj.",
        "adv": "adv.",
        "pron": "pron.",
        "prep": "prep.",
        "conj": "conj.",
        "num": "num.",
        "particle": "part.",
        "interjection": "int.",
    }

    results: dict[str, list[str]] = defaultdict(list)
    for item in rich:
        plain = item.get("plain", "").strip()
        pos_raw = item.get("pos", "")
        pos = pos_map.get(pos_raw, "")
        cn_raw = item.get("cn", "")
        if not plain or not cn_raw:
            continue

        sense = sanitize_sense(pos, plain)
        if not sense:
            continue

        cn_clean = re.sub(r"（.*?）|\(.*?\)|【.*?】|\[.*?\]", "", cn_raw)
        for part in re.split(r"[；;,，、/]+", cn_clean):
            part = part.strip()
            if not part:
                continue
            if not re.match(r"^[\u4e00-\u9fff]+$", part):
                continue
            if sense not in results[part]:
                results[part].append(sense)

    return results


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--input", default="assets/glossary/glossary-ru.tsv", help="现有释义表路径")
    parser.add_argument("--out", default="assets/glossary/glossary-ru.tsv", help="输出释义表路径")
    parser.add_argument("--rich", default=r"C:\Users\32940\WorkBuddy\俄语背单词软件\data\ru-data.js", help="WorkBuddy 俄语语料路径")
    parser.add_argument("--dict", default="assets/lexicon/dict.tsv", help="青简基础词库路径")
    args = parser.parse_args()

    in_path = Path(args.input)
    out_path = Path(args.out)
    rich_path = Path(args.rich)
    dict_path = Path(args.dict)

    # 1. 加载现有 glossary-ru.tsv
    existing_entries: dict[str, list[str]] = {}
    header_comment = "# 由 tools/corpus/glossary_ru.py 生成。词\t[词性. ]译词\t[词性. ]译词\n"
    if in_path.is_file():
        lines = in_path.read_text(encoding="utf-8").splitlines()
        for idx, line in enumerate(lines):
            if idx == 0 and line.startswith("#"):
                header_comment = line + "\n"
                continue
            if line.startswith("#") or not line.strip():
                continue
            parts = line.split("\t")
            word = parts[0].strip()
            senses = [s.strip() for s in parts[1:] if s.strip()]
            if word and senses:
                existing_entries[word] = senses

    old_total = len(existing_entries)
    old_chars = sum(1 for w in existing_entries if len(w) == 1)

    # 2. 准备基础基石词典 (规范化)
    curated_clean: dict[str, list[str]] = {}
    for word, senses in CORE_FOUNDATION_ENTRIES.items():
        valid_senses: list[str] = []
        for s in senses:
            m = re.match(r"^([a-zA-Z]+\.)\s+(.+)$", s)
            if m:
                p, b = m.group(1), m.group(2)
                cs = sanitize_sense(p, b)
                if cs and cs not in valid_senses:
                    valid_senses.append(cs)
            else:
                cs = sanitize_sense("", s)
                if cs and cs not in valid_senses:
                    valid_senses.append(cs)
        if valid_senses:
            curated_clean[word] = valid_senses

    # 3. 从 RICH 语料提炼高频词补充
    rich_entries = extract_from_rich(rich_path)

    # 4. 加载 dict.tsv 词频表，挑选高频缺失词
    high_freq_candidates: list[str] = []
    if dict_path.is_file():
        wmap: dict[str, int] = {}
        for line in dict_path.read_text(encoding="utf-8").splitlines():
            if line.startswith("#") or not line.strip():
                continue
            parts = line.split("\t")
            if len(parts) >= 3:
                w, freq = parts[0], int(parts[2])
                wmap[w] = max(wmap.get(w, 0), freq)
        sorted_dict = sorted(wmap.items(), key=lambda x: x[1], reverse=True)
        # 前 6000 个高频词与前 3000 个单字优先
        high_freq_candidates = [w for w, _ in sorted_dict[:6000]]
        char_candidates = [w for w, _ in sorted_dict if len(w) == 1][:3000]
        high_freq_candidates.extend(char_candidates)

    # 5. 合并策略：
    #    - 现有表已有词：保持现有条目优先（按照工单要求：现有条目保持优先）
    #    - 否则优先使用手工校准词库 (CORE_FOUNDATION_ENTRIES)
    #    - 否则若 RICH 语料中有高频词匹配，则用 RICH 补充
    merged_entries: dict[str, list[str]] = dict(existing_entries)

    added_from_curated = 0
    added_from_rich = 0

    for word, senses in curated_clean.items():
        if word not in merged_entries:
            merged_entries[word] = senses
            added_from_curated += 1

    for word in high_freq_candidates:
        if word in merged_entries:
            continue
        if word in rich_entries:
            # 限制最多取前 2 个释义
            chosen_senses = rich_entries[word][:2]
            if chosen_senses:
                merged_entries[word] = chosen_senses
                added_from_rich += 1

    # 6. 按 Unicode 码点严格递增排序
    sorted_words = sorted(merged_entries.keys())

    # 7. 写入规范 TSV（UTF-8, 无 BOM, LF 换行）
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with out_path.open("w", encoding="utf-8", newline="\n") as f:
        f.write(header_comment)
        for w in sorted_words:
            senses = merged_entries[w]
            line_str = f"{w}\t" + "\t".join(senses) + "\n"
            f.write(line_str)

    new_total = len(merged_entries)
    new_chars = sum(1 for w in merged_entries if len(w) == 1)

    print("=" * 60)
    print(f"俄语释义表扩充完成: {out_path}")
    print(f"原条目数: {old_total} (单字: {old_chars})")
    print(f"基石手工库补入: {added_from_curated}")
    print(f"RICH 语料补入: {added_from_rich}")
    print(f"新条目数: {new_total} (单字: {new_chars}, 净增单字: {new_chars - old_chars})")
    print("=" * 60)
    return 0


if __name__ == "__main__":
    sys.exit(main())
