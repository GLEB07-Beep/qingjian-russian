def build_levels_ru_table() -> list[tuple[str, str]]:
    """去重并生成有序 (词, 等级) 列表。词若重复，归入更早/更简单的等级。"""
    seen: set[str] = set()
    result: list[tuple[str, str]] = []

    for level, words in RAW_LEVEL_DATA:
        level_words: list[str] = []
        for w in words:
            word = w.strip().lower()
            if not word or word in seen:
                continue
            if not CYRILLIC_WORD_PATTERN.match(word):
                raise ValueError(f"Invalid Russian word: {word}")
            seen.add(word)
            level_words.append(word)

        # 按字母序排序该等级内部词汇
        for word in sorted(level_words):
            result.append((word, level))

    return result


def generate_file(out_path: Path | str) -> int:
    """写入 `levels-ru.tsv`，保证 UTF-8、无 BOM、LF 换行。"""
    out_file = Path(out_path)
    out_file.parent.mkdir(parents=True, exist_ok=True)

    entries = build_levels_ru_table()

    lines = [
        HEADER_LINE_1,
        HEADER_LINE_2,
    ]
    for word, level in entries:
        lines.append(f"{word}\t{level}")

    # 二进制写入，确保 LF
    content = "\n".join(lines) + "\n"
    out_file.write_bytes(content.encode("utf-8"))

    print(f"成功生成 {out_file}，收录词汇数: {len(entries)}")
    return 0


def verify_levels_file(path: Path | str) -> tuple[int, list[str]]:
    """门禁校验 `levels-ru.tsv`。

    检测项：
      1. UTF-8 无 BOM
      2. 换行符严格为 LF（禁止 \\r / CRLF）
      3. 首行和第二行等级头严格匹配
      4. 数据行格式为 `word\\tlevel`
      5. 单词为全小写西里尔字母
      6. 等级属于已知等级表
      7. 单词不重复
    """
    path = Path(path)
    if not path.is_file():
        return 0, [f"file not found: {path}"]

    errors: list[str] = []
    raw = path.read_bytes()

    # 1. BOM 检查
    if raw.startswith(b"\xef\xbb\xbf"):
        errors.append("line 1: UTF-8 BOM detected (strictly forbidden)")

    # 2. CRLF 检查
    if b"\r" in raw:
        errors.append("carriage return (\\r) detected; only LF is allowed")

    try:
        text = raw.decode("utf-8")
    except UnicodeDecodeError as e:
        errors.append(f"UTF-8 decode error: {e}")
        return 0, errors

    lines = text.split("\n")
    if lines and not lines[-1]:
        lines.pop()

    if len(lines) < 2:
        errors.append("file too short: missing header lines")
        return 0, errors

    if lines[0] != HEADER_LINE_1:
        errors.append(f"line 1: invalid header comment, expected '{HEADER_LINE_1}', got '{lines[0]}'")

    if lines[1] != HEADER_LINE_2:
        errors.append(f"line 2: invalid levels header, expected '{HEADER_LINE_2}', got '{lines[1]}'")

    valid_levels = set(LEVELS)
    seen_words: set[str] = set()
    ok_count = 0

    for idx, line in enumerate(lines[2:], start=3):
        if not line.strip() or line.startswith("#"):
            continue
        parts = line.split("\t")
        if len(parts) != 2:
            errors.append(f"line {idx}: expected 'word\\tlevel', got '{line}'")
            continue

        word, level = parts[0].strip(), parts[1].strip()
        if not word:
            errors.append(f"line {idx}: empty word")
            continue
        if not level:
            errors.append(f"line {idx}: empty level")
            continue

        if word != word.lower():
            errors.append(f"line {idx}: word '{word}' is not lowercase")

        if not CYRILLIC_WORD_PATTERN.match(word):
            errors.append(f"line {idx}: word '{word}' contains invalid characters")

        if level not in valid_levels:
            errors.append(f"line {idx}: unknown level '{level}' for word '{word}'")

        if word in seen_words:
            errors.append(f"line {idx}: duplicate word '{word}'")
        seen_words.add(word)

        ok_count += 1

    return ok_count, errors


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--build", action="store_true", help="构建 levels-ru.tsv")
    parser.add_argument("--out", default="assets/levels/levels-ru.tsv", help="输出路径")
    parser.add_argument("--verify", metavar="FILE", help="校验 levels-ru.tsv")
    args = parser.parse_args()

    if args.verify:
        ok_count, errors = verify_levels_file(args.verify)
        print(f"校验文件: {args.verify}")
        print(f"有效词条数: {ok_count}")
        print(f"发现错误数: {len(errors)}")
        if errors:
            for e in errors[:20]:
                print(f"  {e}")
            return 1
        print("校验通过：100% 合规！")
        return 0

    if args.build:
        return generate_file(args.out)

    parser.print_help()
    return 0


